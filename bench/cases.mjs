// One answer against the key. got is "YYYY-MM-DDTHH:MM" or null.
export function judge(got, accept) {
  return accept.some((a) => {
    if (a === null) return got === null;
    if (got === null) return false;
    return got.startsWith(a);   // "2026-11-03" accepts any time; "2026-11" any day; "2026-11-03T09:15" needs the time
  });
}
